package com.nookfall.framework.processor;

import java.io.IOException;
import java.io.InputStream;
import java.io.Writer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.function.Function;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.RoundEnvironment;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.NestingKind;
import javax.lang.model.element.TypeElement;
import javax.lang.model.type.DeclaredType;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.ElementFilter;

/**
 * Generates Nookfall registrations for one plugin compilation and validates declarations.
 *
 * <p>Options: {@code nookfall.resources} (resource directory used to validate translations and GUI layouts),
 * {@code nookfall.defaultLocale} (default {@code en_US}), {@code nookfall.plugin} (main class when several
 * {@code JavaPlugin} subclasses exist).
 */
public final class NookfallProcessor extends AbstractProcessor {

    static final String COMPONENTS = "Nookfall_Components";
    static final String PROTOTYPES = "Nookfall_Prototypes";
    static final String CONFIG_REFS = "Nookfall_ConfigRefs";
    private static final List<String> TRIGGERS = List.of(
            Names.COMMAND,
            Names.LISTENER_COMPONENT,
            Names.CONFIG,
            Names.MESSAGES,
            Names.GUI,
            Names.SCHEDULED,
            Names.COMMAND_ARGUMENT);

    private Env env;
    private boolean done;

    @Override
    public synchronized void init(ProcessingEnvironment processingEnv) {
        super.init(processingEnv);
        env = new Env(processingEnv);
    }

    @Override
    public Set<String> getSupportedAnnotationTypes() {
        // Also invoked without Nookfall annotations so a plugin with no components still gets an index.
        return Set.of("*");
    }

    @Override
    public Set<String> getSupportedOptions() {
        return Set.of("nookfall.resources", "nookfall.defaultLocale", "nookfall.plugin", "nookfall.frameworkVersion");
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment round) {
        if (round.processingOver()) {
            return false;
        }
        if (done) {
            for (String trigger : TRIGGERS) {
                for (Element element : annotated(round, trigger)) {
                    env.error(
                            element,
                            "Nookfall annotations in sources generated by other annotation processors are "
                                    + "not supported");
                }
            }
            return false;
        }
        TypeElement main = findMain(round);
        boolean any = TRIGGERS.stream().anyMatch(t -> !annotated(round, t).isEmpty());
        if (main == null) {
            if (any && !env.failed()) {
                Element first = TRIGGERS.stream()
                        .flatMap(t -> annotated(round, t).stream())
                        .findFirst()
                        .orElseThrow();
                env.error(
                        first,
                        "Nookfall components were found but no JavaPlugin subclass is in this compilation. "
                                + "Compile components together with the plugin main class, or set -Anookfall.plugin=<class>");
            }
            done = true;
            return false;
        }
        done = true;
        try {
            generate(round, main);
        } catch (IOException e) {
            env.error(main, "Could not write generated sources: " + e.getMessage());
        }
        return false;
    }

    private Set<? extends Element> annotated(RoundEnvironment round, String name) {
        TypeElement annotation = env.type(name);
        return annotation == null ? Set.of() : round.getElementsAnnotatedWith(annotation);
    }

    private TypeElement findMain(RoundEnvironment round) {
        String configured = processingEnv.getOptions().get("nookfall.plugin");
        if (configured != null) {
            TypeElement type = env.type(configured);
            if (type == null) {
                env.note("nookfall.plugin=" + configured + " was not found");
            }
            return type;
        }
        TypeElement javaPlugin = env.type(Names.JAVA_PLUGIN);
        if (javaPlugin == null) {
            return null;
        }
        List<TypeElement> found = new ArrayList<>();
        for (TypeElement type : ElementFilter.typesIn(round.getRootElements())) {
            if (type.getKind() == ElementKind.CLASS
                    && !type.getModifiers().contains(Modifier.ABSTRACT)
                    && env.isSubtype(type.asType(), Names.JAVA_PLUGIN)) {
                found.add(type);
            }
        }
        if (found.size() > 1) {
            for (TypeElement type : found) {
                env.error(type, "Several JavaPlugin subclasses found; set -Anookfall.plugin=<main class>");
            }
            return null;
        }
        if (found.isEmpty()) {
            return null;
        }
        TypeElement main = found.getFirst();
        if (main.getNestingKind() != NestingKind.TOP_LEVEL) {
            env.error(main, "The plugin main class must be a top-level class");
            return null;
        }
        return main;
    }

    private void generate(RoundEnvironment round, TypeElement main) throws IOException {
        Map<String, PackageModel> packages = new LinkedHashMap<>();
        Function<Element, PackageModel> model = e -> packages.computeIfAbsent(env.packageOf(e), PackageModel::new);
        Set<String> imported = new LinkedHashSet<>();

        // Argument resolvers first: command parameters may use their types.
        Set<String> resolverTypes = new LinkedHashSet<>();
        for (TypeElement type : ElementFilter.typesIn(annotated(round, Names.COMMAND_ARGUMENT))) {
            TypeMirror value = resolvedType(type.asType());
            if (value == null) {
                env.error(type, "@CommandArgument classes must implement ArgumentResolver<T> with a concrete T");
                continue;
            }
            if (!env.checkInstantiable(type)) {
                continue;
            }
            String valueType = env.erasure(value);
            if (!resolverTypes.add(valueType)) {
                env.error(type, "Several @CommandArgument resolvers produce " + valueType);
                continue;
            }
            PackageModel pkg = model.apply(type);
            pkg.arguments.add("new com.nookfall.framework.spi.ArgumentSpec<" + valueType + ">(" + valueType + ".class, "
                    + type.getQualifiedName() + ".class)");
            importBean(pkg, type, false, imported);
        }

        CommandAnalyzer commands = new CommandAnalyzer(env, resolverTypes);
        for (TypeElement type : ElementFilter.typesIn(annotated(round, Names.COMMAND))) {
            String spec = commands.analyze(type);
            if (spec != null) {
                PackageModel pkg = model.apply(type);
                pkg.commands.add(spec);
                importBean(pkg, type, false, imported);
            }
        }

        for (TypeElement type : ElementFilter.typesIn(annotated(round, Names.LISTENER_COMPONENT))) {
            if (!env.checkInstantiable(type)) {
                continue;
            }
            if (!env.isSubtype(type.asType(), Names.LISTENER)) {
                env.error(type, "@ListenerComponent classes must implement org.bukkit.event.Listener");
                continue;
            }
            boolean handlers = env.methods(type).stream().anyMatch(m -> env.has(m, Names.EVENT_HANDLER));
            if (!handlers) {
                env.warn(type, type.getSimpleName() + " has no @EventHandler methods");
            }
            List<String> requires = env.strings(env.annotation(type, Names.LISTENER_COMPONENT), "requiresPlugins");
            PackageModel pkg = model.apply(type);
            pkg.listeners.add("new com.nookfall.framework.spi.ListenerSpec(" + type.getQualifiedName() + ".class, "
                    + Env.listOf(requires) + ")");
            importBean(pkg, type, !requires.isEmpty(), imported);
        }

        GuiAnalyzer guis = new GuiAnalyzer(env);
        for (TypeElement type : ElementFilter.typesIn(annotated(round, Names.GUI))) {
            String binding = guis.analyze(type);
            if (binding != null) {
                PackageModel pkg = model.apply(type);
                pkg.guis.add(binding);
                importBean(pkg, type, false, imported);
            }
        }

        ConfigAnalyzer configs = new ConfigAnalyzer(env);
        for (TypeElement type : ElementFilter.typesIn(annotated(round, Names.CONFIG))) {
            String spec = configs.analyze(type);
            if (spec != null) {
                PackageModel pkg = model.apply(type);
                pkg.configs.add(spec);
                pkg.configTypes.add(type.getQualifiedName().toString());
                pkg.origins.add(type);
            }
        }

        ScheduledAnalyzer scheduled = new ScheduledAnalyzer(env);
        for (ExecutableElement method : ElementFilter.methodsIn(annotated(round, Names.SCHEDULED))) {
            String spec = scheduled.analyze(method);
            if (spec != null) {
                TypeElement owner = (TypeElement) method.getEnclosingElement();
                PackageModel pkg = model.apply(owner);
                pkg.scheduled.add(spec);
                if (!isAvajeBean(owner)) {
                    importBean(pkg, owner, false, imported);
                }
            }
        }

        MessagesAnalyzer messages = new MessagesAnalyzer(env);
        ResourceValidator resources = resourceValidator();
        for (TypeElement type : ElementFilter.typesIn(annotated(round, Names.MESSAGES))) {
            MessagesAnalyzer.Result result = messages.analyze(type);
            if (result == null) {
                continue;
            }
            if (resources != null) {
                resources.checkMessages(type, result.keys());
            }
            String pkg = env.packageOf(type);
            write(pkg.isEmpty() ? result.simpleName() : pkg + "." + result.simpleName(), result.source(), type);
        }
        if (resources != null) {
            guis.declared.forEach((id, declared) -> resources.checkGui(guis.types.get(id), id, declared));
        }

        if (env.failed()) {
            return;
        }
        for (PackageModel pkg : packages.values()) {
            writeComponents(pkg);
        }
        writeIndex(main, packages.values());
        writeMarker(main);
    }

    /**
     * A bean in the main package. Avaje names its module after the packages of source-declared beans and ignores
     * imported ones for that purpose, so without this a plugin whose only components are Nookfall-annotated classes
     * would get no Avaje module.
     */
    private void writeMarker(TypeElement main) throws IOException {
        String pkg = env.packageOf(main);
        String name = main.getSimpleName() + "_NookfallBeans";
        StringBuilder out = header(pkg);
        out.append("@jakarta.inject.Singleton\npublic final class ")
                .append(name)
                .append(" {\n    public ")
                .append(name)
                .append("() {}\n}\n");
        write(pkg.isEmpty() ? name : pkg + "." + name, out.toString(), main);
    }

    private ResourceValidator resourceValidator() {
        String option = processingEnv.getOptions().get("nookfall.resources");
        if (option == null || option.isBlank()) {
            return null;
        }
        Path root = Path.of(option);
        if (!Files.isDirectory(root)) {
            env.note("nookfall.resources directory " + root + " does not exist; skipping resource validation");
            return null;
        }
        return new ResourceValidator(
                env, root, processingEnv.getOptions().getOrDefault("nookfall.defaultLocale", "en_US"));
    }

    private boolean isAvajeBean(TypeElement type) {
        return env.has(type, Names.SINGLETON)
                || env.has(type, Names.AVAJE_COMPONENT)
                || env.has(type, Names.AVAJE_PROTOTYPE)
                || env.has(type, Names.AVAJE_FACTORY)
                || env.has(type, Names.COMMAND)
                || env.has(type, Names.LISTENER_COMPONENT)
                || env.has(type, Names.GUI)
                || env.has(type, Names.COMMAND_ARGUMENT);
    }

    /** Imports the class into Avaje unless it is already an Avaje bean. */
    private void importBean(PackageModel pkg, TypeElement type, boolean prototype, Set<String> imported) {
        pkg.origins.add(type);
        String name = type.getQualifiedName().toString();
        if (env.has(type, Names.SINGLETON)
                || env.has(type, Names.AVAJE_COMPONENT)
                || env.has(type, Names.AVAJE_PROTOTYPE)) {
            return;
        }
        if (type.getNestingKind() != javax.lang.model.element.NestingKind.TOP_LEVEL) {
            // Avaje Inject generates invalid imports for nested classes listed in @Component.Import.
            env.error(
                    type,
                    type.getSimpleName() + " must be a top-level class: Avaje Inject cannot construct nested classes");
            return;
        }
        if (imported.add(name)) {
            (prototype ? pkg.prototypeImports : pkg.singletonImports).add(name);
        }
    }

    private TypeMirror resolvedType(TypeMirror type) {
        for (TypeMirror supertype : env.types.directSupertypes(type)) {
            if (env.isType(supertype, Names.ARGUMENT_RESOLVER)) {
                List<? extends TypeMirror> args = ((DeclaredType) supertype).getTypeArguments();
                return args.size() == 1 && args.get(0) instanceof DeclaredType ? args.get(0) : null;
            }
            TypeMirror nested = resolvedType(supertype);
            if (nested != null) {
                return nested;
            }
        }
        return null;
    }

    private void writeComponents(PackageModel pkg) throws IOException {
        Element[] origins = pkg.origins.toArray(Element[]::new);
        if (!pkg.isEmpty()) {
            StringBuilder out = header(pkg.pkg);
            if (!pkg.singletonImports.isEmpty()) {
                out.append("@io.avaje.inject.Component.Import({")
                        .append(classList(pkg.singletonImports))
                        .append("})\n");
            }
            out.append("@SuppressWarnings({\"unchecked\", \"rawtypes\"})\n");
            out.append("public final class ").append(COMPONENTS).append(" {\n\n");
            out.append("    private ").append(COMPONENTS).append("() {}\n");
            method(out, "com.nookfall.framework.spi.ListenerSpec", "listeners", pkg.listeners);
            method(out, "com.nookfall.framework.spi.CommandSpec<?>", "commands", pkg.commands);
            method(out, "com.nookfall.framework.spi.ArgumentSpec<?>", "arguments", pkg.arguments);
            method(out, "com.nookfall.framework.spi.ConfigSpec<?>", "configs", pkg.configs);
            method(out, "com.nookfall.framework.spi.GuiBinding<?>", "guis", pkg.guis);
            method(out, "com.nookfall.framework.spi.ScheduledSpec<?>", "scheduled", pkg.scheduled);
            out.append("}\n");
            write(pkg.qualified(COMPONENTS), out.toString(), origins);
        }
        if (!pkg.prototypeImports.isEmpty()) {
            StringBuilder out = header(pkg.pkg);
            out.append("@io.avaje.inject.Component.Import(value = {")
                    .append(classList(pkg.prototypeImports))
                    .append("}, kind = io.avaje.inject.Component.Import.Kind.PROTOTYPE)\n");
            out.append("final class ")
                    .append(PROTOTYPES)
                    .append(" {\n    private ")
                    .append(PROTOTYPES)
                    .append("() {}\n}\n");
            write(pkg.qualified(PROTOTYPES), out.toString(), origins);
        }
        if (!pkg.configTypes.isEmpty()) {
            StringBuilder out = header(pkg.pkg);
            out.append("@io.avaje.inject.Factory\n");
            out.append("public final class ").append(CONFIG_REFS).append(" {\n");
            int i = 0;
            for (String type : pkg.configTypes) {
                String simple = type.substring(type.lastIndexOf('.') + 1);
                out.append("\n    @io.avaje.inject.Bean\n    public com.nookfall.framework.config.ConfigRef<")
                        .append(type)
                        .append("> ")
                        .append("config")
                        .append(simple)
                        .append(i++)
                        .append("(com.nookfall.framework.config.ConfigService configs) {\n")
                        .append("        return configs.ref(")
                        .append(type)
                        .append(".class);\n    }\n");
            }
            out.append("}\n");
            write(pkg.qualified(CONFIG_REFS), out.toString(), origins);
        }
    }

    private static StringBuilder header(String pkg) {
        StringBuilder out = new StringBuilder();
        if (!pkg.isEmpty()) {
            out.append("package ").append(pkg).append(";\n\n");
        }
        out.append("@com.nookfall.framework.spi.NookfallGenerated\n");
        return out;
    }

    private static String classList(Set<String> names) {
        List<String> out = new ArrayList<>();
        for (String name : names) {
            out.add(name + ".class");
        }
        return String.join(", ", out);
    }

    private static void method(StringBuilder out, String type, String name, List<String> values) {
        out.append("\n    public static java.util.List<")
                .append(type)
                .append("> ")
                .append(name)
                .append("() {\n");
        if (values.isEmpty()) {
            out.append("        return java.util.List.of();\n    }\n");
            return;
        }
        out.append("        return java.util.List.of(\n                ")
                .append(String.join(",\n                ", values))
                .append(");\n    }\n");
    }

    private void writeIndex(TypeElement main, java.util.Collection<PackageModel> packages) throws IOException {
        String pkg = env.packageOf(main);
        String name = main.getSimpleName() + "_NookfallIndex";
        StringBuilder out = header(pkg);
        out.append("public final class ")
                .append(name)
                .append(" implements com.nookfall.framework.spi.PluginIndex {\n\n");
        out.append("    public ").append(name).append("() {}\n\n");
        out.append("    @Override\n    public String frameworkVersion() {\n        return ")
                .append(Env.literal(frameworkVersion()))
                .append(";\n    }\n");
        String[][] parts = {
            {"com.nookfall.framework.spi.ListenerSpec", "listeners"},
            {"com.nookfall.framework.spi.CommandSpec<?>", "commands"},
            {"com.nookfall.framework.spi.ArgumentSpec<?>", "arguments"},
            {"com.nookfall.framework.spi.ConfigSpec<?>", "configs"},
            {"com.nookfall.framework.spi.GuiBinding<?>", "guis"},
            {"com.nookfall.framework.spi.ScheduledSpec<?>", "scheduled"},
        };
        for (String[] part : parts) {
            out.append("\n    @Override\n    public java.util.List<")
                    .append(part[0])
                    .append("> ")
                    .append(part[1])
                    .append("() {\n        java.util.List<")
                    .append(part[0])
                    .append("> all = new java.util.ArrayList<>();\n");
            for (PackageModel model : packages) {
                if (!model.isEmpty()) {
                    out.append("        all.addAll(")
                            .append(model.qualified(COMPONENTS))
                            .append('.')
                            .append(part[1])
                            .append("());\n");
                }
            }
            out.append("        return java.util.List.copyOf(all);\n    }\n");
        }
        out.append("}\n");
        write(pkg.isEmpty() ? name : pkg + "." + name, out.toString(), main);
    }

    private String frameworkVersion() {
        String override = processingEnv.getOptions().get("nookfall.frameworkVersion");
        if (override != null) {
            return override;
        }
        try (InputStream in = NookfallProcessor.class.getResourceAsStream("/META-INF/nookfall/processor.properties")) {
            Properties properties = new Properties();
            if (in != null) {
                properties.load(in);
            }
            return properties.getProperty("version", "0.0.0");
        } catch (IOException e) {
            return "0.0.0";
        }
    }

    private void write(String name, String source, Element... origins) throws IOException {
        try (Writer writer =
                processingEnv.getFiler().createSourceFile(name, origins).openWriter()) {
            writer.write(source);
        }
    }
}
