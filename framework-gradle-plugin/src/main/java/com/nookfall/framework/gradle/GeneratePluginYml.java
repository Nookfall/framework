package com.nookfall.framework.gradle;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.provider.ListProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.Optional;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;

/** Writes plugin.yml for one packaging mode. */
public abstract class GeneratePluginYml extends DefaultTask {

    @Input
    public abstract Property<String> getPluginName();

    @Input
    public abstract Property<String> getMainClass();

    @Input
    public abstract Property<String> getPluginVersion();

    @Input
    @Optional
    public abstract Property<String> getPluginDescription();

    @Input
    public abstract ListProperty<String> getAuthors();

    @Input
    @Optional
    public abstract Property<String> getWebsite();

    @Input
    public abstract Property<String> getApiVersion();

    @Input
    public abstract ListProperty<String> getDepend();

    @Input
    public abstract ListProperty<String> getSoftDepend();

    @Input
    public abstract ListProperty<String> getLoadBefore();

    @OutputDirectory
    public abstract DirectoryProperty getOutputDirectory();

    @TaskAction
    public void generate() throws IOException {
        String name = getPluginName().get();
        if (!name.matches("[A-Za-z0-9_.-]+")) {
            throw new GradleException("Plugin name '" + name + "' may only contain letters, digits, '_', '.' and '-'");
        }
        StringBuilder yml = new StringBuilder();
        yml.append("# Generated by the Nookfall Gradle plugin.\n");
        yml.append("name: ").append(quote(name)).append('\n');
        yml.append("main: ").append(quote(getMainClass().get())).append('\n');
        yml.append("version: ").append(quote(getPluginVersion().get())).append('\n');
        yml.append("api-version: ").append(quote(getApiVersion().get())).append('\n');
        if (getPluginDescription().isPresent()) {
            yml.append("description: ").append(quote(getPluginDescription().get())).append('\n');
        }
        if (!getAuthors().get().isEmpty()) {
            yml.append("authors: ").append(list(getAuthors().get())).append('\n');
        }
        if (getWebsite().isPresent()) {
            yml.append("website: ").append(quote(getWebsite().get())).append('\n');
        }
        if (!getDepend().get().isEmpty()) {
            yml.append("depend: ").append(list(getDepend().get())).append('\n');
        }
        if (!getSoftDepend().get().isEmpty()) {
            yml.append("softdepend: ").append(list(getSoftDepend().get())).append('\n');
        }
        if (!getLoadBefore().get().isEmpty()) {
            yml.append("loadbefore: ").append(list(getLoadBefore().get())).append('\n');
        }
        Path out = getOutputDirectory().get().getAsFile().toPath();
        Files.createDirectories(out);
        Files.writeString(out.resolve("plugin.yml"), yml.toString(), StandardCharsets.UTF_8);
    }

    private static String list(List<String> values) {
        StringBuilder out = new StringBuilder("[");
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) out.append(", ");
            out.append(quote(values.get(i)));
        }
        return out.append(']').toString();
    }

    private static String quote(String value) {
        return "\"" + value.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
